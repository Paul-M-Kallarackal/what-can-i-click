export function matchCompanyImplementations(
  filters: {
    workload?: WorkloadProfile["workload"];
    mergeFamilyId?: MergeFamilyId;
    mechanismId?: MechanismId;
    query?: string;
  },
  limit = 3,
): ImplementationMatch[] {
  const needle = filters.query?.trim().toLowerCase();

  return COMPANY_IMPLEMENTATIONS.map((implementation) => {
    let score = 0;
    const matchedOn: string[] = [];

    if (filters.workload && implementation.workload === filters.workload) {
      score += 4;
      matchedOn.push(`workload:${filters.workload}`);
    }
    if (filters.mergeFamilyId && implementation.mergeFamilyIds.includes(filters.mergeFamilyId)) {
      score += 6;
      matchedOn.push(`family:${filters.mergeFamilyId}`);
    }
    if (filters.mechanismId && implementation.relatedMechanismIds.includes(filters.mechanismId)) {
      score += 5;
      matchedOn.push(`mechanism:${filters.mechanismId}`);
    }
    if (needle) {
      const haystack = [
        implementation.company,
        implementation.challenge,
        implementation.implementation,
        implementation.outcome,
        implementation.tradeoff,
        ...implementation.mechanisms,
        ...implementation.scale,
      ].join(" ").toLowerCase();
      if (haystack.includes(needle)) {
        score += 3;
        matchedOn.push(`query:${needle}`);
      }
    }

    return { implementation, score, matchedOn };
  })
    .filter((result) => result.score > 0 || (!filters.workload && !filters.mergeFamilyId && !filters.mechanismId && !needle))
    .sort((left, right) => right.score - left.score || left.implementation.company.localeCompare(right.implementation.company))
    .slice(0, Math.max(0, Math.min(limit, 6)));
}

export function companyImplementationById(id: string) {
  return COMPANY_IMPLEMENTATIONS.find((implementation) => implementation.id === id);
}
